using System.Runtime.InteropServices;
using System.Windows.Threading;
namespace PeripheralBattery;

// Explorer can move its topmost taskbar above the card during activation or
// taskbar-button removal. Restore the card on that event, not a second later.
internal sealed class TaskbarLayerWatcher : IDisposable
{
    readonly WinEvent callback;
    readonly IntPtr foregroundHook;
    readonly IntPtr reorderHook;
    readonly Dispatcher dispatcher;
    readonly Action update;
    int pending;
    volatile bool disposed;
    internal TaskbarLayerWatcher(Dispatcher dispatcher,Action update,bool installHooks=true)
    {
        this.dispatcher=dispatcher; this.update=update;
        callback=OnEvent;
        // Out-of-context, skip events generated by our own HWND changes.
        if(installHooks)
        {
            foregroundHook=SetWinEventHook(3,3,IntPtr.Zero,callback,0,0,2);
            reorderHook=SetWinEventHook(0x8004,0x8004,IntPtr.Zero,callback,0,0,2);
        }
    }
    void OnEvent(IntPtr hook,uint eventType,IntPtr window,int objectId,int childId,uint eventThread,uint eventTime)
    {
        if(disposed || (eventType!=3 && !Native.IsTaskbar(window))) return;
        QueueUpdate();
    }
    internal void QueueUpdate()
    {
        if(disposed) return;
        if(Interlocked.Exchange(ref pending,1)!=0) return;
        if(!UiDispatch.Post(dispatcher,()=>!disposed,()=>
        {
            Interlocked.Exchange(ref pending,0);
            update();
        },DispatcherPriority.Render)) Interlocked.Exchange(ref pending,0);
    }
    public void Dispose()
    {
        if(disposed) return; disposed=true;
        if(foregroundHook!=IntPtr.Zero) UnhookWinEvent(foregroundHook);
        if(reorderHook!=IntPtr.Zero) UnhookWinEvent(reorderHook);
    }
    delegate void WinEvent(IntPtr hook,uint eventType,IntPtr window,int objectId,int childId,uint eventThread,uint eventTime);
    [DllImport("user32.dll")] static extern IntPtr SetWinEventHook(uint min,uint max,IntPtr module,WinEvent callback,uint process,uint thread,uint flags);
    [DllImport("user32.dll")] static extern bool UnhookWinEvent(IntPtr hook);
}
